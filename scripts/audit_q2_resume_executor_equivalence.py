"""Compare post-recovery executor outputs with pre-crash formal Q2 outputs."""
import hashlib
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import numpy as np
import pandas as pd

from core.engine import run
from core.protocol import ROOT, save_json


METHODS = ["Always-FT", "EWC", "CLeaR-Predictor", "Proposed"]
FLOAT_SCIENTIFIC = [
    "attack_alpha", "current_service_mse", "candidate_service_mse",
    "deployed_service_mse", "deployed_service_mae", "delta_srv", "downside",
    "U_rec", "U_hist", "median_rec", "mad_rec", "median_hist", "mad_hist",
]
PHYSICAL = {
    "candidate_update_time_s", "verification_time_s", "maintenance_time_s",
    "peak_gpu_memory_bytes",
}


def hash_file(path):
    digest = hashlib.sha256()
    with Path(path).open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def main():
    cfg = {}
    for name in ["frozen_candidate_config.yaml", "frozen_commit_config.yaml", "frozen_baseline_config.yaml"]:
        cfg.update(json.loads((ROOT / "configs" / name).read_text()))
    scratch = ROOT / "scratch/post_q2_executor_benchmark/resume_equivalence"
    scratch.mkdir(parents=True, exist_ok=True)
    records = []
    for method in METHODS:
        name = f"base_13000_7311_GRU_H1_{method}_random_0.05_both_r0.csv"
        reference_path = ROOT / "results/q2_security" / name
        reference = pd.read_csv(reference_path)
        regenerated = pd.DataFrame(run(
            13000, 7311, method, "random", 0.05, "both", cfg,
            backbone="GRU", H=1, run_id=name[:-4],
        ))
        output_path = scratch / name
        regenerated.to_csv(output_path, index=False, na_rep="NA")
        exact_columns = [column for column in reference.columns if column not in set(FLOAT_SCIENTIFIC) | PHYSICAL]
        exact = all(reference[column].fillna("NA").astype(str).equals(regenerated[column].fillna("NA").astype(str)) for column in exact_columns)
        float_diffs = {}
        for column in FLOAT_SCIENTIFIC:
            left = reference[column].to_numpy(dtype=np.float64)
            right = regenerated[column].to_numpy(dtype=np.float64)
            finite = np.isfinite(left) & np.isfinite(right)
            nan_equal = np.array_equal(np.isnan(left), np.isnan(right))
            max_diff = float(np.max(np.abs(left[finite] - right[finite]))) if finite.any() else 0.0
            float_diffs[column] = {"nan_pattern_equal": bool(nan_equal), "max_abs_diff": max_diff}
        max_abs_diff = max(value["max_abs_diff"] for value in float_diffs.values())
        stage_exact = reference["stage"].tolist() == list(range(1, 25)) == regenerated["stage"].tolist()
        passed = exact and stage_exact and max_abs_diff <= 1e-12 and all(v["nan_pattern_equal"] for v in float_diffs.values())
        records.append({
            "method": method, "reference": str(reference_path.relative_to(ROOT)),
            "scratch": str(output_path.relative_to(ROOT)), "rows": len(regenerated),
            "stage_sequence_exact": stage_exact, "hash_integer_categorical_exact": exact,
            "max_abs_float_diff": max_abs_diff, "float_columns": float_diffs,
            "status": "passed" if passed else "failed",
        })
    scientific_files = ["core/engine.py", "core/protocol.py", "core/models.py", "core/joint_dag.py"]
    scientific_hashes = {name: hash_file(ROOT / name) for name in scientific_files}
    aggregate = hashlib.sha256(json.dumps(scientific_hashes, sort_keys=True, separators=(",", ":")).encode()).hexdigest()
    report = {
        "status": "passed" if all(record["status"] == "passed" for record in records) else "failed",
        "scope": "Execution-status retry and internal Q2 phase gate only; no scientific implementation change.",
        "reference_provenance": "Pre-crash formal Q2 CSVs generated by the P7-frozen executor.",
        "cases": records,
        "scientific_core_hashes": scientific_hashes,
        "scientific_core_aggregate_sha256": aggregate,
        "allowed_differences": sorted(PHYSICAL),
    }
    save_json(ROOT / "audits/q2_resume_executor_equivalence.json", report)
    print(json.dumps(report, indent=2), flush=True)
    if report["status"] != "passed":
        raise SystemExit(1)


if __name__ == "__main__":
    main()
